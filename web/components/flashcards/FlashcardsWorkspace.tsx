function dismissedGenerationOperationsStorageKey(
  identity: string,
  courseId: string,
): string {
  return `teeechr:dismissed-flashcard-generation:${encodeURIComponent(identity)}:${encodeURIComponent(courseId)}`;
}

function readDismissedGenerationOperationIds(
  identity: string | null,
  courseId: string | null,
): string[] {
  if (!identity || !courseId || typeof window === "undefined") return [];
  try {
    const stored = window.localStorage.getItem(
      dismissedGenerationOperationsStorageKey(identity, courseId),
    );
    const parsed: unknown = stored ? JSON.parse(stored) : [];
    return Array.isArray(parsed)
      ? parsed.filter((value): value is string => typeof value === "string")
      : [];
  } catch {
    return [];
  }
}

function autoGeneratedDeckTitle(
  focus: string,
  fallback: string,
): string {
  const normalizedFocus = focus.trim().replace(/\s+/g, " ");
  if (!normalizedFocus) return fallback;
  const shortFocus =
    normalizedFocus.length > 56
      ? `${normalizedFocus.slice(0, 53).trimEnd()}…`
      : normalizedFocus;
  return shortFocus;
}

type StudyQueue = "due" | "all" | "missed";
type FlashcardDeckDetailLoadState = "idle" | "loading" | "ready" | "error";
type FlashcardGenerationSupportState = "checking" | "ready" | "error";

export function resolveFlashcardDeckDetailPresentation(
  hasSelectedDeck: boolean,
  hasMatchingView: boolean,
  loadState: FlashcardDeckDetailLoadState,
): "empty" | "opening" | "ready" | "error" {
  if (hasSelectedDeck && hasMatchingView) return "ready";
  if (!hasSelectedDeck) return "empty";
  return loadState === "error" ? "error" : "opening";
}

export function resolveFlashcardGenerationSupportPresentation(
  supportState: FlashcardGenerationSupportState,
  generationAvailable: boolean,
): "checking" | "available" | "unavailable" | "error" {
  if (supportState !== "ready") return supportState;
  return generationAvailable ? "available" : "unavailable";
}

export function isFlashcardDeckLibraryEligible(
  deck: Pick<FlashcardDeck, "mode" | "state" | "ready_at">,
): boolean {
  if (deck.mode === "manual") return true;
  return (
    deck.ready_at !== null &&
    (deck.state === "ready" || deck.state === "archived")
  );
}

/**
 * Generated deck shells intentionally stay out of the study library until
 * publication. Their operation remains the learner's recovery route while it
 * is active, awaiting review, or has failed.
 */
export function hasRecoverableFlashcardGeneration(
  operations: ReadonlyArray<Pick<FlashcardGenerationOperation, "state">>,
): boolean {
  return operations.some(
    (operation) =>
      operation.state !== "completed" && operation.state !== "cancelled",
  );
}

function idempotencyKey(): string {
  return (
    globalThis.crypto?.randomUUID?.() ??
    `flashcard-${Date.now()}-${Math.random().toString(36).slice(2)}`
  );
}

function errorText(cause: unknown): string {
  const message = cause instanceof Error ? cause.message.toLowerCase() : "";
  if (message.includes("stale") || message.includes("revision")) {
    return "This Course changed while you were working. Refresh and try again.";
  }
  if (message.includes("archived")) {
    return "This Course or deck is archived. Restore it before making changes.";
  }
  if (message.includes("not found") || message.includes("404")) {
    return "This Flashcard item is no longer available.";
  }
  return "We could not finish that Flashcard action. Please try again.";
}

